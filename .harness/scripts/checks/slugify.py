#!/usr/bin/env python3
"""Слаг для id правила: кириллица транслитерируется, id остаётся ASCII.

Имя файла правила = имя каталога репродьюсера, и по нему же строится заголовок
коммита. Поэтому id обязан быть без пробелов и без юникода — иначе пара
правило/репродьюсер разъезжается на первой же файловой системе с другой нормализацией.
"""

import re
import sys

TABLE = {
    "а": "a", "б": "b", "в": "v", "г": "g", "д": "d", "е": "e", "ё": "e",
    "ж": "zh", "з": "z", "и": "i", "й": "y", "к": "k", "л": "l", "м": "m",
    "н": "n", "о": "o", "п": "p", "р": "r", "с": "s", "т": "t", "у": "u",
    "ф": "f", "х": "h", "ц": "ts", "ч": "ch", "ш": "sh", "щ": "sch",
    "ъ": "", "ы": "y", "ь": "", "э": "e", "ю": "yu", "я": "ya",
}


def slugify(text, limit=48):
    text = text.strip().lower()
    text = "".join(TABLE.get(ch, ch) for ch in text)
    text = re.sub(r"[^a-z0-9]+", "-", text)
    text = text.strip("-")[:limit].strip("-")
    return text


if __name__ == "__main__":
    print(slugify(sys.stdin.read()))
