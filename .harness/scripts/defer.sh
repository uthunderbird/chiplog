#!/bin/sh
# Отложить побочное направление, не потеряв его.
#
# По ходу задачи всплывает работа, которую видно, но делать сейчас не хочется:
# она размоет диффи и уведёт от того, что делаешь. Молча забыть её — потерять;
# броситься делать — потерять фокус. Третий путь: записать со сроком.
#
#   --now   закрыть в этом коммите, даже если гейт не требует.
#           Гейт будет держать коммит, пока хвост не закрыт работой.
#           Это и есть чистота дерева.
#   --next  переживёт коммит и всплывёт снова.
#
# Срока по умолчанию нет намеренно: решить, когда закрывать, — часть решения
# отложить. Не решил — значит не отложил, а забыл.
set -eu

ROOT=$(cd "$(dirname "$0")/../.." && pwd)

WHEN=""
ARGS=""
set -- "$@"
WHAT=""
WHY=""
for a in "$@"; do
    case "$a" in
        --now)  WHEN="сейчас" ;;
        --next) WHEN="следующим" ;;
        -*) echo "неизвестный флаг: $a" >&2; exit 2 ;;
        *) if [ -z "$WHAT" ]; then WHAT=$a; elif [ -z "$WHY" ]; then WHY=$a; fi ;;
    esac
done

if [ -z "$WHEN" ] || [ -z "$WHAT" ] || [ -z "$WHY" ]; then
    echo "usage: ./.harness/scripts/defer.sh --now|--next \"что отложено\" \"почему не сейчас\"" >&2
    echo "  --now   закрыть в этом коммите — гейт будет держать, пока не закроешь" >&2
    echo "  --next  переживёт коммит" >&2
    echo "  → команда: ./.harness/scripts/defer.sh --next \"что отложено\" \"почему не сейчас\"" >&2
    exit 2
fi

N=$(python3 "$ROOT/.harness/scripts/handoff.py" "$ROOT" add-defer "$WHEN" "$WHAT" "$WHY")
echo "хвост [$N] записан в .harness/handoff.md, срок: $WHEN"
if [ "$WHEN" = "сейчас" ]; then
    echo "коммит закрыт, пока хвост не закрыт работой: handoff.sh --close $N"
else
    echo "коммит закрыт, пока журнал не пересказан человеку"
fi
