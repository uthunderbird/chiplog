#!/bin/sh
# Пороги хайлайтов. Одно место: healthcheck.sh и guard-edit.sh читают отсюда.
# Копия порога разъедется с оригиналом — это уже случалось с дашбордом.
#
# Числа не выдуманы. Замер по 1999 коммитам из пяти локальных репозиториев
# (git log --no-merges -M --name-status, перцентили по числу файлов):
#   размер коммита — медиана 2 файла, p75 4, p90 8, p95 16, p99 100;
#   пауза внутри рабочего дня — медиана 18 мин, p90 195 мин, p95 353 мин.
# Порог обязан ловить выброс, а не регулировать норму: метрика, ставшая целью,
# перестаёт быть метрикой — коммиты начнут резать ради счётчика.

# Незакоммиченная работа, файлов без переименований.
# 10 — это уже две-три порции работы при медиане в 2 файла.
HC_FILES_SOFT=10
# 40 — верхний 1% коммитов. Взводит запрет на правки, поэтому обязан
# срабатывать так редко, чтобы каждое срабатывание запоминалось.
HC_FILES_HARD=40

# Грязное дерево без коммита, часов. p90 паузы — 3,25 ч.
HC_DIRTY_HOURS=4

# Записей в handoff.md. Пересказ двенадцати решений разом — уже не пересказ.
HC_HANDOFF_ENTRIES=5

# AGENTS.md перестал читаться за один присест, слов. Правило §8: гейт умеет блокировать,
# а тут нужно суждение, поэтому носитель — хайлайт с меткой «реши».
HC_AGENTS_WORDS=2000

# Ходов молчания после того, как хайлайт уже прозвучал.
HC_COOLDOWN_TURNS=100

# Захват кейса: выше этих порогов патч не берётся молча — кейс на сорок файлов
# не учит ничему, потому что непонятно, что из них причина.
HC_CASE_MAX_FILES=20
HC_CASE_MAX_BYTES=200000
