#!/bin/sh
# Прогон кейса. Две разные операции, и путать их нельзя.
#
#   --harness case (по умолчанию) — ВОСПРОИЗВЕДЕНИЕ.
#       Мир и харнесс те же, что были. Провал обязан повториться.
#       Доказывает, что кейс валиден.
#
#   --harness <ветка> — ВМЕШАТЕЛЬСТВО.
#       Мир тот же, харнесс сегодняшний. Провал обязан исчезнуть.
#       Доказывает, что правило держит. Это состояние никогда не существовало —
#       поэтому оно не «воспроизведение», и называть его так нельзя.
#
# Второе — исполняемая форма обратного хода из AGENTS.md §3.
#
# Скрипт готовит ворктри и печатает вход. Агента он не запускает: портируемо
# это сделать нельзя, а скрипт, обещающий больше, чем делает, хуже отсутствующего.
set -eu

ROOT=$(cd "$(dirname "$0")/../.." && pwd)
cd "$ROOT"

BASE="${TMPDIR:-/tmp}/harness-replay"
MODE=case
ID=""
CLEAN=0

while [ $# -gt 0 ]; do
    case "$1" in
        --harness) MODE=${2:-case}; shift 2 ;;
        --clean)   CLEAN=1; shift ;;
        -*) echo "неизвестный флаг: $1" >&2; exit 2 ;;
        *)  ID=$1; shift ;;
    esac
done

if [ "$CLEAN" -eq 1 ]; then
    rm -rf "$BASE"
    git worktree prune
    echo "ворктри прогонов убраны, ссылки подчищены"
    exit 0
fi

if [ -z "$ID" ]; then
    echo "id кейса не задан" >&2
    echo "  → команда: ./.harness/scripts/replay.sh <id> [--harness case|<ветка>]," >&2
    echo "    либо ./.harness/scripts/replay.sh --clean для уборки ворктри" >&2
    exit 2
fi

SLUG=$(printf '%s' "$MODE" | tr -c 'a-zA-Z0-9._-' '-')

DIR="$ROOT/.harness/reproducers/$ID"
CASE="$DIR/case.md"

if [ ! -f "$CASE" ]; then
    echo "$DIR/case.md: кейса нет — прогонять нечего" >&2
    echo "  → сделай: заведи кейс ./.harness/scripts/new-case.sh $ID и заполни его" >&2
    echo "  ✓ в каталоге есть case.md с репликами человека и предикатом отказа" >&2
    exit 1
fi

SHA=$(sed -n 's/^commit: *//p' "$CASE" | head -1)
if [ -z "$SHA" ] || [ "$SHA" = "НЕТ-КОММИТОВ" ]; then
    echo "$CASE: не указан commit — состояние мира восстановить не из чего" >&2
    echo "  → сделай: впиши в frontmatter кейса commit: <sha>, на котором случился" >&2
    echo "    провал. Без него ворктри не на что ставить" >&2
    echo "  ✓ git cat-file -e <sha> отвечает без ошибки" >&2
    exit 1
fi
if ! git cat-file -e "${SHA}^{commit}" 2>/dev/null; then
    echo "$CASE: коммита $SHA нет в этом репозитории" >&2
    echo "  → сделай: проверь, что история не переписана и ветка с кейсом на месте" >&2
    echo "  ✓ git cat-file -e $SHA отвечает без ошибки" >&2
    exit 1
fi

WT="$BASE/$ID-$SLUG"
rm -rf "$WT"
mkdir -p "$BASE"
git worktree prune
git worktree add -q --detach "$WT" "$SHA"

# состояние мира на момент провала: незакоммиченное возвращается патчем,
# неотслеживаемое — копированием. git не берёт неотслеживаемое ни одним способом.
if [ -f "$DIR/world.patch" ]; then
    ( cd "$WT" && git apply "$DIR/world.patch" ) \
        && echo "  world.patch применён" \
        || { echo "  world.patch НЕ применился — состояние мира неполное" >&2; }
fi
if [ -d "$DIR/untracked" ]; then
    ( cd "$DIR/untracked" && find . -type f -print ) | while IFS= read -r f; do
        mkdir -p "$WT/$(dirname "$f")"
        cp "$DIR/untracked/$f" "$WT/$f"
    done
    echo "  неотслеживаемые файлы возвращены"
fi

if [ "$MODE" != case ]; then
    # MODE это ref: head по умолчанию, но можно указать ветку или коммит явно.
    if ! H_SHA=$(git rev-parse --verify "$MODE^{commit}" 2>/dev/null); then
        echo "  харнесс: «$MODE» не разрешается в коммит" >&2
        echo "  → команда: ./.harness/scripts/replay.sh <id> --harness <существующая-ветка>" >&2
        exit 1
    fi
    if [ "$H_SHA" = "$(git rev-parse "$SHA^{commit}")" ]; then
        # Молчаливое совпадение — худший исход: прогон выглядит как вмешательство,
        # а является повтором воспроизведения и не доказывает ничего.
        echo "  харнесс из «$MODE» — ТОТ ЖЕ коммит, что у кейса ($SHA)" >&2
        echo "  → сделай: укажи ref с сегодняшним харнессом явно, например" >&2
        echo "    --harness <ветка>. Сейчас HEAD стоит на коммите кейса" >&2
        echo "    (отсоединён или ветка не переключена), и накладывать нечего" >&2
        echo "  ✓ прогон печатает два разных коммита: мир и харнесс" >&2
        exit 1
    fi
    ( cd "$WT" && git checkout "$H_SHA" -- AGENTS.md .harness )
    echo "  харнесс наложен из $MODE ($H_SHA): AGENTS.md + .harness/"
    echo "  незакоммиченные правки внутри .harness/ при этом затёрты — так и надо,"
    echo "  проверяется сегодняшний харнесс, а не тогдашний"
fi

RUNS=$(sed -n 's|^repro: *[0-9]*/||p' "$CASE" | head -1)
case "$RUNS" in ''|*[!0-9]*) RUNS=3 ;; esac

echo
if [ "$MODE" = case ]; then
    echo "ВОСПРОИЗВЕДЕНИЕ — мир и харнесс те, что были на $SHA"
    echo "Ожидаемый исход: провал ПОВТОРЯЕТСЯ. Не повторился — это не кейс,"
    echo "а наблюдение, и его место в .harness/observations.md"
else
    echo "ВМЕШАТЕЛЬСТВО — мир на $SHA, харнесс из $MODE"
    echo "Ожидаемый исход: провал ИСЧЕЗАЕТ. Остался — правило не держит,"
    echo "что бы ни хотелось записать"
fi
echo "Каталог прогона: $WT"
echo

# Подсказки-комментарии вырезаются целым блоком: фильтр по краям пропускает
# середину, и в печатный вход протекает инструкция вместо реплики человека.
section() {
    sed -n "/^## $1/,/^## $2/p" "$CASE" | sed '1d;$d' | sed '/<!--/,/-->/d' | sed '/^[[:space:]]*$/d'
}

echo "--- вход: реплики человека дословно ------------------------------------"
section "Вход" "Предикат"
echo "--- предикат отказа ----------------------------------------------------"
section "Предикат" "Диагноз"
echo "------------------------------------------------------------------------"
echo
echo "Раздел «Диагноз» намеренно не напечатан: это интерпретация агента."
echo "Подашь её на вход — воспроизведёшь правильное поведение, а не провал."
echo
echo "Прогонов сделать: $RUNS. Результат записывается долей, а не флагом."
echo "Убрать ворктри: ./.harness/scripts/replay.sh --clean"
