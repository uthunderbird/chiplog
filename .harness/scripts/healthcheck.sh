#!/bin/sh
# Healthcheck highlights — третий момент речи харнесса.
#
# Дашборд говорит на входе в сессию, гейт — на коммите. Между ними часы работы,
# в которые никто не говорит, и там лежит класс провалов, который гейт не увидит
# никогда: гейт срабатывает на коммите, а провал в том, что коммита нет.
#
# Критерий отбора, по которому не надо спорить:
#   «Если это никогда не дойдёт до коммита — гейт узнает?»
#   Да → это гейт. Нет → это хайлайт.
# Критерий работает в одну сторону: он разрешает добавлять хайлайты, но не
# переносить сюда проверки из гейта. Иначе получится харнесс, который всё
# замечает и ничего не держит.
#
# В норме вывод пуст. Это не оптимизация, а условие существования механизма:
# всё, что печатается на каждом ходу, перестают читать примерно на третьем.
set -eu

cd "${HARNESS_PROJECT_DIR:-${CLAUDE_PROJECT_DIR:-.}}" 2>/dev/null || exit 0
[ -f .harness/scripts/thresholds.sh ] || exit 0
. .harness/scripts/thresholds.sh
git rev-parse --git-dir >/dev/null 2>&1 || exit 0

STATE=.harness/.healthcheck-state
OUT=""
NEW=""

TURN=$(sed -n 's/^#turn //p' "$STATE" 2>/dev/null | head -1)
case "$TURN" in ''|*[!0-9]*) TURN=0 ;; esac
TURN=$((TURN + 1))

# Хайлайт, прозвучавший однажды, замолкает. Он заговорит снова, только если
# уровень вырос или прошло остывание. Без этого условие, истинное три часа,
# превратится в сто одинаковых абзацев — ровно та усталость от тревог,
# от которой весь механизм и заводился.
hl() {
    _id=$1; _lvl=$2
    _text=$(cat)
    _prev=$(grep "^$_id " "$STATE" 2>/dev/null | head -1)
    if [ -n "$_prev" ]; then
        _plvl=$(printf '%s' "$_prev" | cut -d' ' -f2)
        _pturn=$(printf '%s' "$_prev" | cut -d' ' -f3)
        if [ "$_lvl" -le "$_plvl" ] && [ $((TURN - _pturn)) -lt "$HC_COOLDOWN_TURNS" ]; then
            NEW="$NEW$_prev
"
            return 0
        fi
    fi
    OUT="$OUT$_text

"
    NEW="$NEW$_id $_lvl $TURN
"
}

# --- состояние дерева: один вызов git на все проверки ------------------------
PORCELAIN=$(git status --porcelain --untracked-files=all 2>/dev/null || true)
# Переименования не считаем: перенос каталога даёт десятки путей и одну мысль.
# В истории этого репозитория переименования доходили до половины путей
# (git status --porcelain | grep -c '^R').
FILES=$(printf '%s\n' "$PORCELAIN" | grep -c '^[^R]' 2>/dev/null || true)
case "$FILES" in ''|*[!0-9]*) FILES=0 ;; esac
[ -z "$PORCELAIN" ] && FILES=0

# Хайлайт, требующий коммита, обязан знать, что коммит заблокирован выше по течению.
# Иначе он верен по числу и бесполезен по существу: исполнитель делает вывод, что
# тревога врёт, и перестаёт слушать её вместе с соседними.
# Предикат узкий намеренно: он знает контракт заглушки боилерплейта
# (HARNESS_UNCONFIGURED=1), а не всякий способ закрыть гейт. Прогонять сам гейт
# на каждом ходу нельзя — он стоит втрое дороже всего хайлайтчека.
GATE_BLOCKED=""
for a in lint test; do
    if grep -q '^HARNESS_UNCONFIGURED=1' ".harness/scripts/$a.sh" 2>/dev/null; then
        GATE_BLOCKED="$GATE_BLOCKED $a.sh"
    fi
done

# Независимый if, не elif: иначе он подавит жёсткий уровень ниже, и агент увидит
# только требование правки — при том что на жёстком пороге правки заблокированы.
if [ -n "$GATE_BLOCKED" ] && [ "$FILES" -ge "$HC_FILES_HARD" ]; then
    hl gate-blocked 2 <<HL
тупик: правки заблокированы порогом, а разблокировать их можно только правкой
  адаптеры-заглушки:$GATE_BLOCKED, незакоммиченного $FILES файлов
  → стоп: вынеси человеку выбор из двух — вписать стек в адаптеры (тогда гейт
    откроется и дерево можно разгрузить) или поднять порог осознанно. Сам агент
    выйти отсюда не может: закоммитить мешает гейт, а починить гейт мешает
    guard-edit
  ✓ либо адаптеры заполнены и гейт доходит до них, либо порог изменён коммитом
    с обоснованием
HL
elif [ -n "$GATE_BLOCKED" ] && [ "$FILES" -gt 0 ]; then
    hl gate-blocked 1 <<HL
коммит заблокирован не работой, а адаптерами:$GATE_BLOCKED
  → сделай: впиши команды стека в названные адаптеры и удали строку
    HARNESS_UNCONFIGURED=1 — либо вынеси человеку решение, если стек ещё не выбран.
    Пока они заглушки, гейт закрыт, и любое «пора закоммитить» невыполнимо
  ✓ sh .harness/scripts/gate.sh доходит до строк адаптеров и печатает по ним ok
HL
fi

if [ "$FILES" -ge "$HC_FILES_HARD" ]; then
    hl uncommitted 2 <<HL
незакоммиченной работы: $FILES файлов (жёсткий порог $HC_FILES_HARD)
  → сделай: закоммить готовое прямо сейчас, до любой другой работы. Режь по
    смыслу, а не по счётчику: один коммит — одна мысль. Правки файлов
    заблокированы, пока дерево не разгружено ниже $HC_FILES_HARD
  ✗ не сваливай всё в один коммит ради счётчика: граница коммита это точка
    отката, а не способ погасить предупреждение
  ✓ git status показывает меньше $HC_FILES_SOFT файлов, и каждый коммит
    читается по заголовку
HL
elif [ "$FILES" -ge "$HC_FILES_SOFT" ]; then
    hl uncommitted 1 <<HL
незакоммиченной работы: $FILES файлов (порог $HC_FILES_SOFT)
  → сделай: предложи человеку закоммитить то, что уже готово, прежде чем
    браться за следующее. При медиане коммита в 2 файла это две-три порции
    работы: откатываться некуда, любая ошибка стоит всего накопленного
  ✓ дерево разгружено, и у работы появилась точка отката
HL
fi

# --- давно без коммита при грязном дереве ------------------------------------
if [ "$FILES" -gt 0 ]; then
    LAST=$(git log -1 --format=%ct 2>/dev/null || echo 0)
    NOW=$(date +%s)
    HOURS=$(( (NOW - LAST) / 3600 ))
    if [ "$LAST" -gt 0 ] && [ "$HOURS" -ge "$HC_DIRTY_HOURS" ]; then
        hl stale 1 <<HL
последний коммит был $HOURS ч назад, дерево всё это время грязное
  → сделай: предложи человеку закоммитить готовое. Файлов может быть немного,
    но работа без точки отката копится уже $HOURS часов
  ✓ последний коммит моложе $HC_DIRTY_HOURS ч либо дерево чистое
HL
    fi
fi

# --- отсоединённый HEAD ------------------------------------------------------
if ! git symbolic-ref -q HEAD >/dev/null 2>&1 && [ "$FILES" -gt 0 ]; then
    hl detached 1 <<HL
HEAD отсоединён, и в дереве $FILES изменённых файлов
  → стоп: вынеси человеку выбор из двух — завести ветку от текущего состояния
    или работать в отрыве сознательно. Чек видит отсоединённую голову,
    но не знает, нарочно она отсоединена или это остаток прошлой операции
  ✗ не коммить в отсоединённую голову: коммит не будет принадлежать ни одной
    ветке и потеряется при первом же переключении
  ✓ git symbolic-ref HEAD отвечает именем ветки, либо решение записано
    через ./.harness/scripts/decide.sh
HL
fi

# --- журнал хвостов распух ---------------------------------------------------
if [ -f .harness/handoff.md ]; then
    ENTRIES=$(grep -c '^## ' .harness/handoff.md 2>/dev/null || true)
    case "$ENTRIES" in ''|*[!0-9]*) ENTRIES=0 ;; esac
    if [ "$ENTRIES" -ge "$HC_HANDOFF_ENTRIES" ]; then
        hl handoff 1 <<HL
в .harness/handoff.md накопилось записей: $ENTRIES (порог $HC_HANDOFF_ENTRIES)
  → сделай: перескажи журнал человеку сейчас, не дожидаясь коммита. Гейт
    поймает его и на коммите, но пересказ дюжины решений разом — уже не
    пересказ: ценность падает с размером партии
  ✓ ./.harness/scripts/handoff.sh --ack прошёл, и человек услышал каждое
    решение отдельно
HL
    fi
fi

# --- крючок долга: появился первый заведённый вход ---------------------------
# Долг, привязанный к событию, обязан заговорить сам в момент, когда событие
# наступило. Иначе «подождём до первого применения» неотличимо от «забыли».
#
# Считаем каталоги входа, а не правила: норма живёт без входа, и правило-норма
# крючок D25 не взводит. И гасим по наблюдаемому следу — когда строка долга
# уходит из модели, уходит и её формулировка крючка, а с ней и этот хайлайт.
REPROS=0
for d in .harness/reproducers/*/; do
    [ -d "$d" ] || continue
    if [ -n "$(ls -A "$d" 2>/dev/null | grep -v '^README.md$')" ]; then
        REPROS=$((REPROS + 1))
    fi
done
if [ "$REPROS" -gt 0 ] && grep -q "первый заведённый вход" HARNESS_MODEL.md 2>/dev/null; then
    hl debts-armed 1 <<HL
заведено каталогов входа: $REPROS — крючок долга сработал
  → реши: в «Текущих долгах» есть запись, ждавшая именно первого входа: до него
    форма была неизвестна, и принуждение писалось бы вслепую. Пример появился —
    закрой долг работой либо перенеси, назвав причину и дату следующей ретро.
    Отсрочка допускается один раз: на второй решает человек.
    Решение запиши: ./.harness/scripts/decide.sh "перенёс долг D25"
    "одного входа мало, чтобы задать форму" "закрыть по первому входу"
  ✓ строка долга ушла из HARNESS_MODEL.md — тогда и этот хайлайт замолчит сам
HL
fi

# --- AGENTS.md перестал читаться за один присест -----------------------------
if [ -f AGENTS.md ]; then
    WORDS=$(wc -w < AGENTS.md | tr -d ' ')
    if [ "$WORDS" -ge "$HC_AGENTS_WORDS" ]; then
        hl agents-size 1 <<HL
AGENTS.md вырос до $WORDS слов (порог $HC_AGENTS_WORDS)
  → реши: перечитай его и реши сам, что сжать, слить или вынести в скрипт —
    либо запиши, почему файл честно такой длины. Порог решает, когда спросить,
    но не каков ответ: это правило-суждение из §8, а не счётчик.
    Решение запиши: ./.harness/scripts/decide.sh "оставил AGENTS.md как есть"
    "каждый раздел закрыт гейтом" "вынести часть в отдельный файл"
  ✓ файл читается за один присест — либо в журнале решений записано,
    почему он честно такой
HL
    fi
fi

# --- запись состояния и вывод ------------------------------------------------
{ printf '#turn %s\n' "$TURN"; printf '%s' "$NEW"; } > "$STATE"

[ -n "$OUT" ] && printf 'здоровье репозитория:\n\n%s' "$OUT"
exit 0
