#!/bin/sh
# Записать решение, принятое за человека.
#
# Агент вправе решать всё, что выясняется чтением: истории, копилки, прогоном
# входа. Но решение, принятое молча, — это выбор ветки без флага, то есть ровно
# то, что AGENTS.md §2 объявил провалом. Поэтому решать можно, молчать нельзя:
# выбор падает в журнал, журнал закрывает коммит, коммит открывает человек.
#
# Формат журнала живёт в handoff.py — здесь только проверка аргументов.
set -eu

ROOT=$(cd "$(dirname "$0")/../.." && pwd)

if [ $# -lt 2 ]; then
    echo "usage: ./.harness/scripts/decide.sh \"что решил\" \"на чём основано\" [\"отклонённая альтернатива\"]" >&2
    echo "  → команда: ./.harness/scripts/decide.sh \"что решил\" \"на чём основано\"" >&2
    exit 2
fi

N=$(python3 "$ROOT/.harness/scripts/handoff.py" "$ROOT" add-decision "$1" "$2" "${3:-}")
echo "решение [$N] записано в .harness/handoff.md"
echo "коммит закрыт, пока журнал не пересказан человеку"
