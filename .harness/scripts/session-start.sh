#!/bin/sh
# Что агент видит на входе в сессию. Вешается на SessionStart.
#
# Логика живёт здесь, а не в строке команды внутри .claude/settings.json,
# по одной причине: строку в JSON приходится экранировать, и человек, решивший
# проверить собственный конфиг копипастой в терминал, получает бэкслеши
# в команде и ошибку вместо дашборда. Конфиг харнесса обязан проверяться руками.
set -eu

cd "${CLAUDE_PROJECT_DIR:-.}" 2>/dev/null || exit 0

# Харнесса в проекте может не быть: хук приезжает с шаблоном и не должен
# ронять ошибку каждую сессию там, где .harness/ уже удалили.
[ -f .harness/scripts/dashboard.sh ] || exit 0

sh .harness/scripts/dashboard.sh || true
