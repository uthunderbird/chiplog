#!/bin/sh
# Жёсткий уровень хайлайта: не громче, а другим механизмом.
#
# Предупреждение, которое можно проигнорировать, обучает игнорированию — и
# первым перестанут читать мягкий уровень. Поэтому там, где нужно ограничение,
# стоит ограничение: отказ на PreToolUse для Edit/Write.
#
# И оно закрывает работу, а не коммит. Рефлекс «заблокировать коммит» здесь
# строго вреден: проблема в том, что коммита нет. Единственный путь вперёд
# должен вести через коммит, а не мимо него.
#
# exit 2 — блокирующий отказ, stderr возвращается агенту.
set -eu

cd "${CLAUDE_PROJECT_DIR:-.}" 2>/dev/null || exit 0
[ -f .harness/scripts/thresholds.sh ] || exit 0
. .harness/scripts/thresholds.sh
git rev-parse --git-dir >/dev/null 2>&1 || exit 0

PORCELAIN=$(git status --porcelain 2>/dev/null || true)
FILES=$(printf '%s\n' "$PORCELAIN" | grep -c '^[^R]' 2>/dev/null || true)
case "$FILES" in ''|*[!0-9]*) FILES=0 ;; esac
[ -z "$PORCELAIN" ] && FILES=0

[ "$FILES" -lt "$HC_FILES_HARD" ] && exit 0

cat >&2 <<HL
    правки заблокированы: незакоммиченной работы $FILES файлов при пороге $HC_FILES_HARD
      → сделай: закоммить готовое, режь по смыслу — один коммит одна мысль.
        Блокировка снимется сама, как только дерево опустится ниже $HC_FILES_HARD.
        Порог живёт в .harness/scripts/thresholds.sh: считаешь его неверным —
        чини порог и запиши решение, а не обходи проверку
      ✗ не обходи через git commit --no-verify и не отключай хук ради одной
        правки: обход виден в истории по отсутствию коммита рядом
      ✓ git status показывает меньше $HC_FILES_HARD файлов
HL
exit 2
